// Generates docs/BUFFERS.md and the generated blocks of README.md / README.zh-CN.md.
//
//   node scripts/gen-docs.ts          write
//   node scripts/gen-docs.ts --check  fail if anything is out of date (CI)
//
// README numbers and examples come from here (and from benchmark/results.json), never from memory.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SYSTEMS } from '../src/data/systems.ts';
import { REAGENTS } from '../src/data/reagents.ts';
import { molarMass } from '../src/elements.ts';
import { pKAt } from '../src/model.ts';
import { CERTIFIED_STEPS } from '../src/recipe.ts';
import { main } from '../src/cli.ts';
import { predict } from '../src/recipe.ts';

const root = join(import.meta.dirname, '..');
const check = process.argv.includes('--check');
let stale = false;

function write(path: string, content: string) {
  const full = join(root, path);
  let old = '';
  try { old = readFileSync(full, 'utf8'); } catch { /* new file */ }
  if (old === content) return;
  if (check) { console.error(`${path} is out of date: run node scripts/gen-docs.ts`); stale = true; } else writeFileSync(full, content);
}

function replaceBlock(text: string, name: string, body: string): string {
  const re = new RegExp(`(<!-- ${name}:start -->\\n)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(text)) throw new Error(`block ${name} not found`);
  return text.replace(re, `$1${body}$2`);
}

const sign = (x: number) => (x < 0 ? '−' : '') + Math.abs(x);
const charge = (z: number) => (z === 0 ? '0' : z > 0 ? `+${z === 1 ? '' : z}`.replace(/^\+$/, '+1') : `−${-z}`);

// ---- docs/BUFFERS.md ----
let md = `# Buffers and reagents

Generated by \`node scripts/gen-docs.ts\` from \`src/data/systems.ts\` and \`src/data/reagents.ts\`. Do not edit by hand.

## Acid–base systems

${SYSTEMS.length} systems from Goldberg, Kishore & Lennen, *J. Phys. Chem. Ref. Data* **31**, 231 (2002), Section 8 (pp. 359–360).
Values are for 298.15 K, 0.1 MPa and zero ionic strength. ΔH in kJ/mol, ΔCp in J/(K·mol); "≈" marks values the paper
prints as approximate and "—" a value it does not give. Charges are those of the acid and base species of each step.
dpK/dT is at 25 °C. ✓ marks a step exercised by a NIST certified standard in the benchmark.

| System | Step | pK | ΔH | ΔCp | Charges | dpK/dT (/°C) | Source |
|---|---:|---:|---:|---:|:---:|---:|---|
`;
for (const s of SYSTEMS) {
  s.steps.forEach((st, j) => {
    const zA = s.z0 - j;
    const ap = (k: 'pK' | 'dH' | 'dCp') => (st.approx?.includes(k) ? '≈' : '');
    const dpdt = st.dH === null ? '—' : (pKAt(st, 25.5) - pKAt(st, 24.5)).toFixed(4).replace('-', '−');
    const name = j === 0 ? `**${s.name}**${s.zh !== s.name ? ` ${s.zh}` : ''}` : '';
    const pK = st.assumed ? '(strong)' : `${ap('pK')}${sign(st.pK)}${CERTIFIED_STEPS[s.id]?.includes(j) ? ' ✓' : ''}`;
    md += `| ${name} | ${j + 1} | ${pK} | ${st.dH === null ? '—' : ap('dH') + sign(st.dH)} | ${st.dCp === null ? '—' : ap('dCp') + sign(st.dCp)} | ${charge(zA)} / ${charge(zA - 1)} | ${st.assumed ? '' : dpdt} | ${j === 0 ? `§${s.section}, p. ${s.page}` : ''} |\n`;
  });
}
md += `\nNotes on individual systems:\n\n`;
for (const s of SYSTEMS) for (const n of s.notes ?? []) md += `- **${s.name}**: ${n.en}\n`;
md += `
## Reagents

Molar masses are computed from the formulas with the CIAAW 2024 abridged standard atomic weights. Check the formula
against the label of the bottle you use: hydrates differ in mass.

| id | Substance | Formula | g/mol | System | Role |
|---|---|---|---:|---|---|
`;
for (const r of REAGENTS) md += `| \`${r.id}\` | ${r.name} | ${r.formula} | ${molarMass(r.formula).toFixed(2)} | ${r.system ?? ''} | ${r.role}${r.state === 'liquid' ? ' (liquid)' : ''} |\n`;
write('docs/BUFFERS.md', md);

// ---- README blocks ----
const results = JSON.parse(readFileSync(join(root, 'benchmark', 'results.json'), 'utf8'));
const def = results.models.find((m: { model: string }) => m.model === results.defaultModel);
const byModel = (m: string) => results.models.find((x: { model: string }) => x.model === m);
const label: Record<string, [string, string]> = { davies: ['Davies (default)', 'Davies（默认）'], 'bates-guggenheim': ['Bates–Guggenheim', 'Bates–Guggenheim'], ideal: ['Ideal solution (no activity correction)', '理想溶液（不计活度）'] };
const accuracy = (zh: boolean) => {
  let t = zh
    ? `| 活度模型 | 认证值个数 | 最大 \\|Δ\\| | \\|Δ\\| 中位数 |\n|---|---:|---:|---:|\n`
    : `| Activity model | Certified values | Max \\|Δ\\| | Median \\|Δ\\| |\n|---|---:|---:|---:|\n`;
  for (const m of ['davies', 'bates-guggenheim', 'ideal']) { const r = byModel(m); t += `| ${label[m]![zh ? 1 : 0]} | ${r.n} | ${r.maxAbs.toFixed(3)} | ${r.medianAbs.toFixed(3)} |\n`; }
  t += zh
    ? `\n${def.standards.length} 种 NIST 标准物质（磷酸盐两种配比、邻苯二甲酸氢钾、硼砂、碳酸盐、Tris），0–50 °C 下证书所列的每个温度，Δ = 计算值 − 认证值（pH）。\n`
    : `\n${def.standards.length} NIST Standard Reference Materials (phosphate at two ratios, potassium hydrogen phthalate, borax, carbonate, Tris) at every temperature on their certificates, 0–50 °C. Δ = computed − certified, in pH units.\n`;
  return t;
};
const demo = (args: string[], lang: 'en' | 'zh') => {
  const r = main([...args, ...(lang === 'zh' ? ['--lang', 'zh'] : [])]);
  return '```text\n$ bufferbench ' + args.join(' ') + (lang === 'zh' ? ' --lang zh' : '') + '\n' + r.stdout + '\n```\n';
};
const DEMO = ['recipe', 'tris', '--conc', '50mM', '--ph', '8.0', '--temp', '4', '--prep-temp', '22'];
const phos = { kh2po4: 0.01, na2hpo4: 0.01 };
const saltShift = predict({ amounts: { ...phos, nacl: 0.15 }, t: 25 }).pH - predict({ amounts: phos, t: 25 }).pH;
const trisAmounts = { tris: 0.05, hcl: 0.03 };
const coldShift = predict({ amounts: trisAmounts, tPrep: 22, t: 4 }).pH - predict({ amounts: trisAmounts, tPrep: 22, t: 22 }).pH;
const effects = (zh: boolean) => zh
  ? `- 20 mM 磷酸盐缓冲液（KH₂PO₄ + Na₂HPO₄ 各 10 mM）加入 150 mM NaCl 后，25 °C 下 pH 预计变化 ${saltShift.toFixed(2).replace("-", "−")}（离子强度超过 0.1，属外推）。\n- 22 °C 配好的 50 mM Tris 缓冲液（30 mM HCl）冷到 4 °C，pH 预计变化 +${coldShift.toFixed(2)}。\n`
  : `- Adding 150 mM NaCl to a 20 mM phosphate buffer (10 mM each of KH₂PO₄ and Na₂HPO₄) is predicted to change its pH at 25 °C by ${saltShift.toFixed(2).replace("-", "−")} (ionic strength above 0.1: extrapolated).\n- A 50 mM Tris buffer (30 mM HCl) made up at 22 °C is predicted to change by +${coldShift.toFixed(2)} when cooled to 4 °C.\n`;
const counts = (zh: boolean) => zh ? `${SYSTEMS.length} 个酸碱体系、${REAGENTS.length} 种试剂` : `${SYSTEMS.length} acid–base systems and ${REAGENTS.length} reagents`;
for (const [file, zh] of [['README.md', false], ['README.zh-CN.md', true]] as const) {
  let text = readFileSync(join(root, file), 'utf8');
  text = replaceBlock(text, 'accuracy', accuracy(zh));
  text = replaceBlock(text, 'demo', demo(DEMO, zh ? 'zh' : 'en'));
  text = replaceBlock(text, 'effects', effects(zh));
  text = text.replace(/<!-- counts:start -->[\s\S]*?<!-- counts:end -->/, `<!-- counts:start -->${counts(zh)}<!-- counts:end -->`);
  write(file, text);
}

if (check) { if (stale) process.exit(1); console.log('docs up to date'); } else console.log('docs written');
