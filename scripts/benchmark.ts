// Scores the model against the NIST certified pH standards in benchmark/certified.ts.
//
//   node scripts/benchmark.ts          write benchmark/results.json and docs/VALIDATION.md
//   node scripts/benchmark.ts --check  fail if the committed files differ from a fresh run, or if the
//                                      default model exceeds the accuracy gate
//
// Nothing here is fitted: the constants come from Goldberg et al. (2002), the water properties from
// IAPWS, and the certificates are only compared against.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CERTIFIED } from '../benchmark/certified.ts';
import { solve } from '../src/equilibrium.ts';
import { compositionFromMolalities } from '../src/mixture.ts';
import { ACTIVITY_MODELS, type ActivityModel } from '../src/model.ts';
import { getReagent } from '../src/data/reagents.ts';
import { VERSION } from '../src/version.ts';

/** The default model must reproduce every certified value within this many pH units. */
export const GATE = 0.025;
const DEFAULT_MODEL: ActivityModel = 'davies';

const root = join(import.meta.dirname, '..');
const r4 = (x: number) => Math.round(x * 1e4) / 1e4;

interface Point { t: number; certified: number; computed: number; delta: number }
interface StandardResult { id: string; name: string; source: string; covers: string; uncertainty: number; ionicStrength: number; points: Point[]; maxAbs: number; mean: number }
interface ModelResult { model: ActivityModel; standards: StandardResult[]; n: number; maxAbs: number; medianAbs: number; rms: number; withinUncertainty: number }

function run(model: ActivityModel): ModelResult {
  const standards: StandardResult[] = [];
  const all: number[] = [];
  let within = 0;
  for (const c of CERTIFIED) {
    const comp = compositionFromMolalities(c.composition);
    const points: Point[] = Object.entries(c.values).map(([t, v]) => {
      const pH = solve(comp, { tC: Number(t), model }).pH;
      return { t: Number(t), certified: v, computed: r4(pH), delta: r4(pH - v) };
    });
    for (const p of points) { all.push(Math.abs(p.delta)); if (Math.abs(p.delta) <= c.uncertainty) within++; }
    const deltas = points.map((p) => p.delta);
    standards.push({
      id: c.id, name: c.name, source: c.source, covers: c.covers, uncertainty: c.uncertainty,
      ionicStrength: r4(solve(comp, { tC: 25, model }).ionicStrength),
      points,
      maxAbs: r4(Math.max(...deltas.map(Math.abs))),
      mean: r4(deltas.reduce((a, b) => a + b, 0) / deltas.length),
    });
  }
  const sorted = [...all].sort((a, b) => a - b);
  const mid = sorted.length / 2;
  const median = sorted.length % 2 ? sorted[Math.floor(mid)]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
  return {
    model, standards, n: all.length,
    maxAbs: r4(Math.max(...all)),
    medianAbs: r4(median),
    rms: r4(Math.sqrt(all.reduce((a, b) => a + b * b, 0) / all.length)),
    withinUncertainty: within,
  };
}

const results = ACTIVITY_MODELS.map(run);
const json = JSON.stringify({ tool: 'bufferbench', version: VERSION, defaultModel: DEFAULT_MODEL, gate: GATE, models: results }, null, 2) + '\n';

const fmt = (x: number) => (x > 0 ? '+' : x < 0 ? '−' : '±') + Math.abs(x).toFixed(3);
const byModel = (m: ActivityModel) => results.find((r) => r.model === m)!;
const def = byModel(DEFAULT_MODEL);
const std = (id: string) => def.standards.find((x) => x.id === id)!;

let md = `# Validation against NIST certified pH standards

Generated by \`node scripts/benchmark.ts\` (bufferbench ${VERSION}). Do not edit by hand.

The model predicts the pH of ${CERTIFIED.length} NIST Standard Reference Material buffers at every temperature their certificates give,
${def.n} points in all from 0 to 50 °C. The inputs are only the composition on the certificate and the temperature; the
ionization constants come from Goldberg et al. (2002) and the properties of water from IAPWS. No parameter was fitted to these
values. A calibrated pH meter reports the same conventional pH that the certificates certify.

## Summary

| Activity model | Points | Max \\|Δ\\| | Median \\|Δ\\| | RMS | Within the certificate's uncertainty |
|---|---:|---:|---:|---:|---:|
`;
for (const r of results) md += `| ${r.model}${r.model === DEFAULT_MODEL ? ' (default)' : ''} | ${r.n} | ${r.maxAbs.toFixed(3)} | ${r.medianAbs.toFixed(3)} | ${r.rms.toFixed(3)} | ${r.withinUncertainty} of ${r.n} |\n`;
md += `
Δ = computed − certified, in pH units. CI fails if the default model's largest deviation exceeds ${GATE}.
The ideal-solution row leaves activity coefficients out (a Henderson–Hasselbalch calculation with thermodynamic pK values,
corrected for temperature). It shows what the activity correction is worth; calculators that use apparent pKa values measured
at some ionic strength will differ from it in either direction.

## Per standard (${DEFAULT_MODEL} model)

| Standard | Chemistry | I (mol/kg) | Max \\|Δ\\| | Mean Δ | Certificate U | Source |
|---|---|---:|---:|---:|---:|---|
`;
for (const s of def.standards) md += `| ${s.name} | ${s.covers} | ${s.ionicStrength.toFixed(3)} | ${s.maxAbs.toFixed(3)} | ${fmt(s.mean)} | ${s.uncertainty.toFixed(3)} | ${s.source} |\n`;
md += `
## Every point (${DEFAULT_MODEL} model)

| Standard | ${[0, 5, 10, 15, 20, 25, 30, 35, 37, 40, 45, 50].map((t) => `${t} °C`).join(' | ')} |
|---|${[0, 5, 10, 15, 20, 25, 30, 35, 37, 40, 45, 50].map(() => '---:').join('|')}|
`;
for (const s of def.standards) {
  md += `| ${s.name} | ${[0, 5, 10, 15, 20, 25, 30, 35, 37, 40, 45, 50].map((t) => { const p = s.points.find((x) => x.t === t); return p ? fmt(p.delta) : ''; }).join(' | ')} |\n`;
}
md += `
## Reading the results

- The deviations are nearly constant across temperature for each standard. The temperature dependence (van 't Hoff with
  ΔH and ΔCp) is therefore not where the model falls short; the offsets come from the activity model and from specific ion
  interactions that a charge-only model leaves out.
- **Tris** is the only cationic acid among the standards (TrisH⁺ ⇌ Tris + H⁺); its mean deviation is ${fmt(std('srm922-923').mean)}.
  Predictions for other amine buffers that buffer the same way (Bis-tris, imidazole, triethanolamine…) carry a note saying so.
- **Carbonate** deviates by ${fmt(std('srm191d').mean)} on average. The two phosphate standards share the same constants and nearly the
  same ionic strength, yet their mean deviations differ by ${Math.abs(std('srm186-1to1').mean - std('srm186-1to3.5').mean).toFixed(3)}, which a model without
  sodium/potassium-specific terms cannot reproduce.
- The IUPAC 2002 recommendations (Buck et al., Pure Appl. Chem. 74, 2169, Table 2) list "typical" pH(PS) values for the same
  primary standards and say they should not replace the certified value of a specific batch. For the 1:3.5 phosphate at 50 °C
  the typical value (7.367) is 0.018 below the NIST certificate (7.3848). This benchmark uses the certificates.
- Two certificates (SRM 186-g, issued 2003, and SRM 922/923, revised 1993) come from NIST's certificate archive because the
  current ones were not retrievable; later lots may differ by a few thousandths.

## What this does not cover

- Ionic strength above 0.1 mol/kg. Typical biological buffers with 150 mM NaCl sit near 0.2; results there carry the tier
  "extrapolated".
- Good's buffers (HEPES, MOPS, PIPES…), for which no certified standard is used here. Their constants are NIST-evaluated, and
  the same model applies, but the tier is "model", not "checked".
- Mixtures with Mg²⁺ or Ca²⁺ that bind the buffer.
`;

const ranges: Record<string, [number, number]> = {};
for (const c of CERTIFIED) {
  const temps = Object.keys(c.values).map(Number);
  for (const id of Object.keys(c.composition)) {
    const sys = getReagent(id).system;
    if (!sys) continue;
    const r = ranges[sys] ?? [Infinity, -Infinity];
    ranges[sys] = [Math.min(r[0], ...temps), Math.max(r[1], ...temps)];
  }
}
let maxI = 0;
for (const c of CERTIFIED) {
  const comp = compositionFromMolalities(c.composition);
  for (const t of Object.keys(c.values).map(Number)) maxI = Math.max(maxI, solve(comp, { tC: t, model: DEFAULT_MODEL }).ionicStrength);
}
const ideal = byModel('ideal');
const idealMin = Math.min(...ideal.standards.map((s) => s.maxAbs));
const accuracy = `// Generated by scripts/benchmark.ts from the NIST certified standards. Do not edit by hand.
export const CHECKED_STANDARDS = ${CERTIFIED.length};
export const CHECKED_POINTS = ${def.n};
/** Largest |computed − certified| of the default model, pH units. */
export const CHECKED_MAX_DEVIATION = ${def.maxAbs.toFixed(3)};
export const CHECKED_MEDIAN_DEVIATION = ${def.medianAbs.toFixed(3)};
/** Temperature range (°C) of the certified values for each system a standard exercises. */
export const CERTIFIED_T_RANGE: Readonly<Record<string, readonly [number, number]>> = {
${Object.entries(ranges).sort().map(([k, [a, b]]) => `  ${k}: [${a}, ${b}],`).join('\n')}
};
/** Highest ionic strength (mol/kg) among the certified standards, rounded up: the \"checked\" tier stops here. */
export const CHECKED_MAX_IONIC_STRENGTH = ${(Math.ceil(maxI * 1000) / 1000).toFixed(3)};
/** Smallest and largest per-standard maximum deviation of the ideal-solution model, pH units. */
export const IDEAL_DEVIATION_RANGE: readonly [number, number] = [${idealMin.toFixed(2)}, ${ideal.maxAbs.toFixed(2)}];
`;
const resultsPath = join(root, 'benchmark', 'results.json');
const accuracyPath = join(root, 'src', 'accuracy.ts');
const mdPath = join(root, 'docs', 'VALIDATION.md');
if (process.argv.includes('--check')) {
  let failed = false;
  for (const [path, fresh] of [[resultsPath, json], [mdPath, md], [accuracyPath, accuracy]] as const) {
    let old = '';
    try { old = readFileSync(path, 'utf8'); } catch { /* missing */ }
    if (old !== fresh) { console.error(`${path} is out of date: run node scripts/benchmark.ts`); failed = true; }
  }
  if (def.maxAbs > GATE) { console.error(`default model deviates by ${def.maxAbs} > gate ${GATE}`); failed = true; }
  if (failed) process.exit(1);
  console.log(`benchmark ok: ${def.n} certified points, max |Δ| ${def.maxAbs} ≤ ${GATE}`);
} else {
  writeFileSync(resultsPath, json);
  writeFileSync(mdPath, md);
  writeFileSync(accuracyPath, accuracy);
  for (const r of results) console.log(`${r.model.padEnd(17)} n=${r.n} max|Δ| ${r.maxAbs.toFixed(4)} median ${r.medianAbs.toFixed(4)} rms ${r.rms.toFixed(4)} within U ${r.withinUncertainty}/${r.n}`);
}
